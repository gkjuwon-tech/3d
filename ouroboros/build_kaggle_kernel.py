"""
OUROBOROS Kaggle 발사대 조립기.

모듈 01~07 소스를 한 파일(ouroboros_runner.py)에 담아 Kaggle 스크립트 커널로 만듭니다.
커널이 시작되면 모듈들을 풀어놓고 데몬을 시간 예산(--hours)만큼 돌린 뒤,
/kaggle/working 에 체크포인트·텔레메트리·차트·진화 DNA를 남깁니다.
/kaggle/input 아래에 이전 세션 체크포인트가 붙어 있으면 자동으로 이어받습니다.

사용법:
    python build_kaggle_kernel.py --user gk1212 --hours 11.0
    KAGGLE_API_TOKEN=... kaggle kernels push -p kaggle_kernel
"""

from __future__ import annotations
import argparse
import base64
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

RUNNER_TEMPLATE = '''"""
PROJECT OUROBOROS v2 | Kaggle Infinite Evolution Runner (auto-generated by build_kaggle_kernel.py)
"""
import base64
import os
import runpy
import sys

MODULES = {modules}

SRC_DIR = "/tmp/ouroboros_src"
OUT_DIR = "/kaggle/working" if os.path.isdir("/kaggle/working") else os.path.abspath("ouroboros_out")
os.makedirs(SRC_DIR, exist_ok=True)
os.makedirs(OUT_DIR, exist_ok=True)
for name, blob in MODULES.items():
    with open(os.path.join(SRC_DIR, name), "wb") as f:
        f.write(base64.b64decode(blob))
sys.path.insert(0, SRC_DIR)

sys.argv = [
    "OUROBOROS_07_kaggle_infinite_daemon.py",
    "--out", OUT_DIR,
    "--epochs", "{epochs}",
    "--hours", "{hours}",
    "--seed", "{seed}",
    "--resume-from", "/kaggle/input",
]
runpy.run_path(os.path.join(SRC_DIR, "OUROBOROS_07_kaggle_infinite_daemon.py"), run_name="__main__")
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True, help="Kaggle 사용자명")
    ap.add_argument("--slug", default="ouroboros-infinite-evolution")
    ap.add_argument("--title", default="OUROBOROS Infinite Evolution")
    ap.add_argument("--hours", type=float, default=11.0)
    ap.add_argument("--epochs", type=int, default=10_000_000)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--resume-kernel", action="append", default=[],
                    help="이전 세션 출력을 이어받을 커널 (예: gk1212/ouroboros-infinite-evolution)")
    ap.add_argument("--gpu", action="store_true", help="numpy 전용이라 기본은 CPU 세션")
    ap.add_argument("--out", default=os.path.join(HERE, "kaggle_kernel"))
    args = ap.parse_args()

    modules = {}
    for path in sorted(glob.glob(os.path.join(HERE, "OUROBOROS_0[1-7]_*.py"))):
        with open(path, "rb") as f:
            modules[os.path.basename(path)] = base64.b64encode(f.read()).decode("ascii")
    assert len(modules) == 7, f"모듈 7개가 필요합니다: {sorted(modules)}"

    os.makedirs(args.out, exist_ok=True)
    runner = RUNNER_TEMPLATE.format(
        modules=json.dumps(modules, indent=4),
        epochs=args.epochs,
        hours=args.hours,
        seed=args.seed,
    )
    with open(os.path.join(args.out, "ouroboros_runner.py"), "w", encoding="utf-8") as f:
        f.write(runner)

    metadata = {
        "id": f"{args.user}/{args.slug}",
        "title": args.title,
        "code_file": "ouroboros_runner.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(args.gpu),
        "enable_tpu": False,
        "enable_internet": False,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": args.resume_kernel,
        "model_sources": [],
    }
    with open(os.path.join(args.out, "kernel-metadata.json"), "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2, ensure_ascii=False)
    print(f"Kaggle kernel bundle -> {args.out} ({metadata['id']}, {args.hours}h, modules={len(modules)})")


if __name__ == "__main__":
    main()
